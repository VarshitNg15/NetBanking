CREATE TABLE AUTH_USER (
    USER_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID            VARCHAR2(50),
    EMAIL                  VARCHAR2(255) NOT NULL,
    PASSWORD_HASH          VARCHAR2(255) NOT NULL,
    ACCOUNT_STATUS         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    EMAIL_VERIFIED         CHAR(1) DEFAULT 'N' NOT NULL,
    MFA_ENABLED            CHAR(1) DEFAULT 'Y' NOT NULL,
    FAILED_LOGIN_ATTEMPTS  NUMBER DEFAULT 0 NOT NULL,
    LOCKED_UNTIL           TIMESTAMP,
    LAST_LOGIN_AT          TIMESTAMP,
    CREATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_AUTH_USER PRIMARY KEY (USER_ID),
    CONSTRAINT UK_AUTH_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_AUTH_USER_CUSTOMER_ID UNIQUE (CUSTOMER_ID),

    CONSTRAINT CK_AUTH_USER_STATUS
        CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'LOCKED', 'DISABLED', 'BLOCKED', 'PENDING_APPROVAL')),

    CONSTRAINT CK_AUTH_USER_EMAIL_VERIFIED
        CHECK (EMAIL_VERIFIED IN ('Y', 'N')),

    CONSTRAINT CK_AUTH_USER_MFA_ENABLED
        CHECK (MFA_ENABLED IN ('Y', 'N')),

    CONSTRAINT CK_AUTH_USER_FAILED_ATTEMPTS
        CHECK (FAILED_LOGIN_ATTEMPTS >= 0)
);


CREATE TABLE USER_ROLE (
    USER_ROLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID      NUMBER NOT NULL,
    ROLE_NAME    VARCHAR2(30) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_USER_ROLE
        PRIMARY KEY (USER_ROLE_ID),

    CONSTRAINT FK_USER_ROLE_AUTH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES AUTH_USER(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_USER_ROLE_NAME
        CHECK (ROLE_NAME IN ('CUSTOMER', 'ADMIN')),

    CONSTRAINT UK_USER_ROLE
        UNIQUE (USER_ID, ROLE_NAME)
);

CREATE TABLE EMAIL_OTP (
    OTP_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER NOT NULL,
    OTP_HASH        VARCHAR2(255) NOT NULL,
    OTP_PURPOSE     VARCHAR2(30) NOT NULL,
    EXPIRES_AT      TIMESTAMP NOT NULL,
    VERIFIED_AT     TIMESTAMP,
    ATTEMPT_COUNT   NUMBER DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_EMAIL_OTP
        PRIMARY KEY (OTP_ID),

    CONSTRAINT FK_EMAIL_OTP_AUTH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES AUTH_USER(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_EMAIL_OTP_PURPOSE
        CHECK (
            OTP_PURPOSE IN (
                'LOGIN',
                'PASSWORD_RESET',
                'EMAIL_VERIFICATION'
            )
        ),

    CONSTRAINT CK_EMAIL_OTP_ATTEMPT_COUNT
        CHECK (ATTEMPT_COUNT >= 0)
);

CREATE TABLE REFRESH_TOKEN (
    REFRESH_TOKEN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID          NUMBER NOT NULL,
    TOKEN_HASH       VARCHAR2(500) NOT NULL,
    EXPIRES_AT       TIMESTAMP NOT NULL,
    REVOKED_AT       TIMESTAMP,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_REFRESH_TOKEN
        PRIMARY KEY (REFRESH_TOKEN_ID),

    CONSTRAINT FK_REFRESH_TOKEN_AUTH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES AUTH_USER(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_REFRESH_TOKEN_HASH
        UNIQUE (TOKEN_HASH)
);


CREATE TABLE PASSWORD_RESET_TOKEN (
    RESET_TOKEN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID        NUMBER NOT NULL,
    TOKEN_HASH     VARCHAR2(500) NOT NULL,
    EXPIRES_AT     TIMESTAMP NOT NULL,
    USED_AT        TIMESTAMP,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PASSWORD_RESET_TOKEN
        PRIMARY KEY (RESET_TOKEN_ID),

    CONSTRAINT FK_PASSWORD_RESET_AUTH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES AUTH_USER(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_PASSWORD_RESET_TOKEN_HASH
        UNIQUE (TOKEN_HASH)
);


CREATE TABLE LOGIN_HISTORY (
    LOGIN_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID          NUMBER NOT NULL,
    LOGIN_STATUS     VARCHAR2(30) NOT NULL,
    IP_ADDRESS       VARCHAR2(45),
    USER_AGENT       VARCHAR2(500),
    LOGIN_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_LOGIN_HISTORY
        PRIMARY KEY (LOGIN_HISTORY_ID),

    CONSTRAINT FK_LOGIN_HISTORY_AUTH_USER
        FOREIGN KEY (USER_ID)
        REFERENCES AUTH_USER(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_LOGIN_HISTORY_STATUS
        CHECK (
            LOGIN_STATUS IN (
                'SUCCESS',
                'FAILED',
                'LOGOUT',
                'LOCKED'
            )
        )
);


