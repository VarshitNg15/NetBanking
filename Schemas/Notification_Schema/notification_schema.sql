CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY,

    EVENT_ID VARCHAR2(100)
        CONSTRAINT UQ_NOTIFICATIONS_EVENT_ID UNIQUE
        CONSTRAINT NN_NOTIFICATIONS_EVENT_ID NOT NULL,

    EVENT_TYPE VARCHAR2(100)
        CONSTRAINT NN_NOTIFICATIONS_EVENT_TYPE NOT NULL,

    CUSTOMER_ID VARCHAR2(50)
        CONSTRAINT NN_NOTIFICATIONS_CUSTOMER_ID NOT NULL,

    RECIPIENT_EMAIL VARCHAR2(255)
        CONSTRAINT NN_NOTIFICATIONS_EMAIL NOT NULL,

    SUBJECT VARCHAR2(255)
        CONSTRAINT NN_NOTIFICATIONS_SUBJECT NOT NULL,

    MESSAGE_BODY CLOB
        CONSTRAINT NN_NOTIFICATIONS_MESSAGE NOT NULL,

    STATUS VARCHAR2(20) DEFAULT 'PENDING'
        CONSTRAINT NN_NOTIFICATIONS_STATUS NOT NULL,

    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP
        CONSTRAINT NN_NOTIFICATIONS_CREATED_AT NOT NULL,

    SENT_AT TIMESTAMP(6),

    FAILURE_REASON VARCHAR2(1000),

    CONSTRAINT CK_NOTIFICATIONS_STATUS
        CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED'))
);


COMMENT ON TABLE NOTIFICATIONS IS
    'Logical notifications created from Kafka domain events.';
COMMENT ON COLUMN NOTIFICATIONS.EVENT_ID IS
    'Kafka event identifier used as the notification idempotency key.';
COMMENT ON COLUMN NOTIFICATIONS.CUSTOMER_ID IS
    'Customer reference owned by the User/Auth domain; no cross-schema FK.';
COMMENT ON COLUMN NOTIFICATIONS.STATUS IS
    'Notification state: PENDING, SENT, or FAILED.';


CREATE TABLE NOTIFICATION_DELIVERY (
    DELIVERY_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_NOTIFICATION_DELIVERY PRIMARY KEY,

    NOTIFICATION_ID NUMBER(19)
        CONSTRAINT NN_NOTIFICATION_DELIVERY_NOTIFICATION NOT NULL,

    ATTEMPT_NUMBER NUMBER(5)
        CONSTRAINT NN_NOTIFICATION_DELIVERY_ATTEMPT NOT NULL,

    SMTP_PROVIDER VARCHAR2(50) DEFAULT 'GOOGLE_SMTP'
        CONSTRAINT NN_NOTIFICATION_DELIVERY_PROVIDER NOT NULL,

    DELIVERY_STATUS VARCHAR2(20)
        CONSTRAINT NN_NOTIFICATION_DELIVERY_STATUS NOT NULL,

    ATTEMPTED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP
        CONSTRAINT NN_NOTIFICATION_DELIVERY_ATTEMPTED NOT NULL,

    DELIVERED_AT TIMESTAMP(6),

    ERROR_CODE VARCHAR2(100),

    ERROR_MESSAGE VARCHAR2(1000),

    RESPONSE_MESSAGE VARCHAR2(1000),

    MESSAGE_ID VARCHAR2(255),

    CONSTRAINT FK_NOTIFICATION_DELIVERY_NOTIFICATION
        FOREIGN KEY (NOTIFICATION_ID)
        REFERENCES NOTIFICATIONS (NOTIFICATION_ID),

    CONSTRAINT CK_NOTIFICATION_DELIVERY_ATTEMPT
        CHECK (ATTEMPT_NUMBER > 0),

    CONSTRAINT CK_NOTIFICATION_DELIVERY_PROVIDER
        CHECK (SMTP_PROVIDER IN ('GOOGLE_SMTP', 'MOCK_SMTP', 'DEV_SMTP', 'AWS_SES')),

    CONSTRAINT CK_NOTIFICATION_DELIVERY_STATUS
        CHECK (DELIVERY_STATUS IN ('SUCCESS', 'FAILED'))
);



COMMENT ON TABLE NOTIFICATION_DELIVERY IS
    'Individual email delivery attempts for a notification.';
COMMENT ON COLUMN NOTIFICATION_DELIVERY.SMTP_PROVIDER IS
    'SMTP provider required by the current functional requirements.';



CREATE TABLE AUDIT_LOGS (
    AUDIT_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUDIT_LOGS PRIMARY KEY,

    EVENT_ID VARCHAR2(100)
        CONSTRAINT UQ_AUDIT_LOGS_EVENT_ID UNIQUE,

    EVENT_TYPE VARCHAR2(100)
        CONSTRAINT NN_AUDIT_LOGS_EVENT_TYPE NOT NULL,

    ACTOR_ID VARCHAR2(50),

    ACTOR_ROLE VARCHAR2(20),

    CUSTOMER_ID VARCHAR2(50),

    RESOURCE_TYPE VARCHAR2(50),

    RESOURCE_ID VARCHAR2(100),

    ACTION VARCHAR2(100)
        CONSTRAINT NN_AUDIT_LOGS_ACTION NOT NULL,

    DESCRIPTION VARCHAR2(1000),

    IP_ADDRESS VARCHAR2(45),

    USER_AGENT VARCHAR2(500),

    EVENT_TIMESTAMP TIMESTAMP(6) DEFAULT SYSTIMESTAMP
        CONSTRAINT NN_AUDIT_LOGS_TIMESTAMP NOT NULL,

    CONSTRAINT CK_AUDIT_LOGS_ACTOR_ROLE
        CHECK (ACTOR_ROLE IS NULL OR ACTOR_ROLE IN ('CUSTOMER', 'ADMIN'))
);



COMMENT ON TABLE AUDIT_LOGS IS
    'Audit records owned by Notification Service for application activity.';
COMMENT ON COLUMN AUDIT_LOGS.ACTOR_ID IS
    'Actor reference identifier; identity is owned by Auth/User Service.';
COMMENT ON COLUMN AUDIT_LOGS.RESOURCE_ID IS
    'Referenced resource identifier; resource ownership remains with the source service.';


CREATE TABLE AUDIT_ACCESS_REQUESTS (
    REQUEST_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUDIT_ACCESS_REQUESTS PRIMARY KEY,

    ADMIN_ID VARCHAR2(50)
        CONSTRAINT NN_AUDIT_ACCESS_REQUESTS_ADMIN NOT NULL,

    STATUS VARCHAR2(20) DEFAULT 'PENDING'
        CONSTRAINT NN_AUDIT_ACCESS_REQUESTS_STATUS NOT NULL,

    REQUESTED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP
        CONSTRAINT NN_AUDIT_ACCESS_REQUESTS_REQUESTED NOT NULL,

    APPROVED_BY VARCHAR2(50),

    APPROVED_AT TIMESTAMP(6),

    EXPIRES_AT TIMESTAMP(6),

    REASON VARCHAR2(500),

    CONSTRAINT CK_AUDIT_ACCESS_REQUESTS_STATUS
        CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED'))
);


COMMENT ON TABLE AUDIT_ACCESS_REQUESTS IS
    'Temporary authorization requests for protected audit-log access.';
COMMENT ON COLUMN AUDIT_ACCESS_REQUESTS.ADMIN_ID IS
    'Admin reference identifier; admin identity is owned by Auth/User Service.';


CREATE TABLE AUDIT_ACCESS_TOKENS (
    TOKEN_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_AUDIT_ACCESS_TOKENS PRIMARY KEY,

    REQUEST_ID NUMBER(19)
        CONSTRAINT NN_AUDIT_ACCESS_TOKENS_REQUEST NOT NULL,

    TOKEN_HASH VARCHAR2(255)
        CONSTRAINT NN_AUDIT_ACCESS_TOKENS_HASH NOT NULL,

    ISSUED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP
        CONSTRAINT NN_AUDIT_ACCESS_TOKENS_ISSUED NOT NULL,

    EXPIRES_AT TIMESTAMP(6)
        CONSTRAINT NN_AUDIT_ACCESS_TOKENS_EXPIRES NOT NULL,

    USED_AT TIMESTAMP(6),

    STATUS VARCHAR2(20) DEFAULT 'ACTIVE'
        CONSTRAINT NN_AUDIT_ACCESS_TOKENS_STATUS NOT NULL,

    CONSTRAINT FK_AUDIT_ACCESS_TOKENS_REQUEST
        FOREIGN KEY (REQUEST_ID)
        REFERENCES AUDIT_ACCESS_REQUESTS (REQUEST_ID),

    CONSTRAINT UQ_AUDIT_ACCESS_TOKENS_HASH UNIQUE (TOKEN_HASH),

    CONSTRAINT CK_AUDIT_ACCESS_TOKENS_STATUS
        CHECK (STATUS IN ('ACTIVE', 'USED', 'EXPIRED', 'REVOKED'))
);


COMMENT ON TABLE AUDIT_ACCESS_TOKENS IS
    'Hashed, temporary, one-time audit access authorization tokens.';
COMMENT ON COLUMN AUDIT_ACCESS_TOKENS.TOKEN_HASH IS
    'Hash of the temporary approval token; plaintext token must not be stored.';



