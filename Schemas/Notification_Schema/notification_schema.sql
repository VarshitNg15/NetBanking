    ON AUDIT_ACCESS_REQUESTS (EXPIRES_AT);

CREATE INDEX IDX_AUDIT_TOKENS_REQUEST
    ON AUDIT_ACCESS_TOKENS (REQUEST_ID);

CREATE INDEX IDX_AUDIT_TOKENS_STATUS
    ON AUDIT_ACCESS_TOKENS (STATUS);

CREATE INDEX IDX_AUDIT_TOKENS_EXPIRY
    ON AUDIT_ACCESS_TOKENS (EXPIRES_AT);


