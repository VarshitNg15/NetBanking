-- ============================================================
-- USER SERVICE TABLES
-- ============================================================

-- 1. CUSTOMER
CREATE TABLE CUSTOMER (
    CUSTOMER_ID        VARCHAR2(20) PRIMARY KEY,

    CUSTOMER_STATUS    VARCHAR2(30) NOT NULL,

    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT CK_CUSTOMER_STATUS
        CHECK (
            CUSTOMER_STATUS IN (
                'PENDING_APPROVAL',
                'ACTIVE',
                'INACTIVE',
                'BLOCKED'
            )
        )
);


-- 2. CUSTOMER_PROFILE
CREATE TABLE CUSTOMER_PROFILE (
    CUSTOMER_ID        VARCHAR2(20) PRIMARY KEY,

    FIRST_NAME         VARCHAR2(100) NOT NULL,

    LAST_NAME          VARCHAR2(100),

    DATE_OF_BIRTH      DATE,

    PHONE_NUMBER       VARCHAR2(20),

    ADDRESS_LINE1      VARCHAR2(255),

    ADDRESS_LINE2      VARCHAR2(255),

    CITY               VARCHAR2(100),

    STATE              VARCHAR2(100),

    POSTAL_CODE        VARCHAR2(20),

    COUNTRY            VARCHAR2(100),

    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_PROFILE_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID)
        ON DELETE CASCADE
);


-- 3. ACCOUNT_OPENING_REQUEST
CREATE TABLE ACCOUNT_OPENING_REQUEST (
    REQUEST_ID         VARCHAR2(30) PRIMARY KEY,

    CUSTOMER_ID        VARCHAR2(20) NOT NULL,

    REQUEST_STATUS     VARCHAR2(20) NOT NULL,

    SUBMITTED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    REVIEWED_BY        VARCHAR2(50),

    REVIEWED_AT        TIMESTAMP,

    REJECTION_REASON   VARCHAR2(500),

    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_REQUEST_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT CK_REQUEST_STATUS
        CHECK (
            REQUEST_STATUS IN (
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        )
);


-- 4. ACCOUNT_OPENING_REQUEST_TYPE
CREATE TABLE ACCOUNT_OPENING_REQUEST_TYPE (
    REQUEST_TYPE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY
                       PRIMARY KEY,

    REQUEST_ID         VARCHAR2(30) NOT NULL,

    ACCOUNT_TYPE       VARCHAR2(20) NOT NULL,

    CONSTRAINT FK_REQUEST_TYPE_REQUEST
        FOREIGN KEY (REQUEST_ID)
        REFERENCES ACCOUNT_OPENING_REQUEST(REQUEST_ID)
        ON DELETE CASCADE,

    CONSTRAINT CK_REQUEST_ACCOUNT_TYPE
        CHECK (
            ACCOUNT_TYPE IN (
                'SAVINGS',
                'CURRENT'
            )
        ),

    CONSTRAINT UK_REQUEST_ACCOUNT_TYPE
        UNIQUE (REQUEST_ID, ACCOUNT_TYPE)
);


CREATE INDEX IDX_CUSTOMER_STATUS
    ON CUSTOMER(CUSTOMER_STATUS);

CREATE INDEX IDX_REQUEST_CUSTOMER
    ON ACCOUNT_OPENING_REQUEST(CUSTOMER_ID);

CREATE INDEX IDX_REQUEST_STATUS
    ON ACCOUNT_OPENING_REQUEST(REQUEST_STATUS);

CREATE INDEX IDX_REQUEST_TYPE_REQUEST
    ON ACCOUNT_OPENING_REQUEST_TYPE(REQUEST_ID);


SELECT TABLE_NAME
FROM USER_TABLES
ORDER BY TABLE_NAME;

SELECT
    TABLE_NAME,
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN (
    'CUSTOMER',
    'CUSTOMER_PROFILE',
    'ACCOUNT_OPENING_REQUEST',
    'ACCOUNT_OPENING_REQUEST_TYPE'
)
ORDER BY TABLE_NAME, CONSTRAINT_NAME;