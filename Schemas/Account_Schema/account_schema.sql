-- ============================================================
-- 11. PROTECT ACCOUNT LEDGER
--
-- Prevent UPDATE and DELETE.
-- Ledger is append-only.
-- ============================================================

CREATE OR REPLACE TRIGGER TRG_LEDGER_IMMUTABLE
BEFORE UPDATE OR DELETE ON ACCOUNT_LEDGER
BEGIN

    RAISE_APPLICATION_ERROR(
        -20001,
        'ACCOUNT_LEDGER is append-only. UPDATE and DELETE are not allowed.'
    );

END;
/




-- ============================================================
-- 12. ACCOUNT BALANCE VIEW
-- ============================================================

CREATE OR REPLACE VIEW V_ACCOUNT_BALANCE AS
SELECT
    A.ACCOUNT_ID,
    A.CUSTOMER_ID,
    A.ACCOUNT_NUMBER,
    A.ACCOUNT_TYPE,
    A.ACCOUNT_STATUS,
    A.CURRENCY_CODE,
    B.CURRENT_BALANCE,
    B.AVAILABLE_BALANCE,
    B.TOTAL_CREDIT,
    B.TOTAL_DEBIT,
    B.VERSION_NO
FROM ACCOUNT A
JOIN ACCOUNT_BALANCE B
    ON A.ACCOUNT_ID = B.ACCOUNT_ID;


